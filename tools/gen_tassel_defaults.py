import sys, yaml
src = sys.argv[1]
d = yaml.safe_load(open(src))

PLOTTED = ["branch_internode_length","branch_internode_thickness","lateral_insertion_angle",
"lateral_internode_length","lateral_node_count","peduncle_branch_probability","spike_internode_length",
"spike_internode_thickness","spike_zone_branch_probability","main_pair_proximal_scale_x",
"main_pair_proximal_scale_y","main_pair_proximal_scale_z","main_pair_proximal_angle",
"main_pair_internode_length","main_pair_internode_thickness","main_pair_internode_angle",
"main_pair_distal_scale_x","main_pair_distal_scale_y","main_pair_distal_scale_z","main_pair_distal_angle",
"branch_pair_proximal_scale_x","branch_pair_proximal_scale_y","branch_pair_proximal_scale_z",
"branch_pair_proximal_angle","branch_pair_internode_length","branch_pair_internode_thickness",
"branch_pair_internode_angle","branch_pair_distal_scale_x","branch_pair_distal_scale_y",
"branch_pair_distal_scale_z","branch_pair_distal_angle","lateral_initiation_delay_gdd",
"spike_anthesis_offset_gdd","primary_lateral_branch_probability","secondary_lateral_branch_probability"]
CURVE = ["rachis_elongation_curve","rachis_thickness_curve","lateral_elongation_curve",
"lateral_thickness_curve","lateral_angle_development_curve","pair_proximal_scale_curve",
"pair_proximal_angle_curve","pair_internode_length_curve","pair_internode_thickness_curve",
"pair_internode_angle_curve","pair_distal_scale_curve","pair_distal_angle_curve"]
# field -> yaml key (identity unless listed)
SINGLE = {f:f for f in ["branch_node_count","spike_node_count","phyllotaxis_angle","branch_azimuth_offset",
"lateral_thickness_ratio","final_age_gdd","secondary_insertion_angle","secondary_internode_length",
"secondary_internode_thickness","secondary_node_count","target_gdd","gdd_per_day","plastochron_gdd",
"anthesis_gdd","main_axis_plastochron_scale","lateral_axis_plastochron_scale","lateral_bud_plastochron_scale",
"maturity_initiation_coupling","reference_maturity_gdd","branch_angle_relaxation","pair_angle_relaxation",
"stage_1_end_t","stage_2_end_t","stage_3_end_t","secondary_ramp_start_t","secondary_ramp_end_t",
"mature_droop_start_t","mature_droop_strength"]}
SINGLE["maturity_gdd"] = "max_gdd"

def fl(x):
    s = f"{float(x):.9g}"
    if ("." not in s) and ("e" not in s) and ("E" not in s) and ("inf" not in s) and ("nan" not in s):
        s += ".0"
    return s + "f"
def vals(curve):
    pts = curve["values_"]
    return "{ " + ", ".join("{"+fl(p[0])+", "+fl(p[1])+"}" for p in pts) + " }"

def emit_single(dst, node):
    L=[]
    if isinstance(node, dict):
        L.append(f"  d.{dst}.mean = {fl(node['mean'])};")
        L.append(f"  d.{dst}.deviation = {fl(node.get('deviation',0.0))};")
    else:
        L.append(f"  d.{dst}.mean = {fl(node)};")
        L.append(f"  d.{dst}.deviation = 0.0f;")
    return L

def emit_plot(prefix, node):
    L=[]
    L.append(f"  {prefix}.min_value = {fl(node['min_value'])};")
    L.append(f"  {prefix}.max_value = {fl(node['max_value'])};")
    c=node["curve"]
    L.append(f"  {prefix}.curve.SetTangent({'true' if c.get('tangent_',True) else 'false'});")
    L.append(f"  {prefix}.curve.UnsafeGetValues() = {vals(c)};")
    return L

def emit_plotted(dst, node):
    return emit_plot(f"d.{dst}.mean", node["mean"]) + emit_plot(f"d.{dst}.deviation", node["deviation"])

def emit_curve(dst, node):
    L=[]
    L.append(f"  d.{dst}.SetTangent({'true' if node.get('tangent_',True) else 'false'});")
    L.append(f"  d.{dst}.UnsafeGetValues() = {vals(node)};")
    return L

out=[]
out.append("// GENERATED by tools/gen_tassel_defaults.py from MaizeTasselDescriptor_Default.mtassel.")
out.append("// Do not edit by hand. Encodes the tuned maize-tassel genotype as C++ setters.")
out.append('#include "lsystem/TasselDescriptor.hpp"')
out.append("")
out.append("namespace l_system_plugin {")
out.append("")
out.append("void ApplyMaizeTasselDefaults(TasselDescriptor& d) {")
for f,key in SINGLE.items():
    if key in d: out += emit_single(f, d[key])
for f in PLOTTED:
    if f in d: out += emit_plotted(f, d[f])
for f in CURVE:
    if f in d: out += emit_curve(f, d[f])
# tropisms
n = int(d.get("tropism_count",0))
out.append("")
out.append("  d.tropisms.clear();")
for i in range(n):
    p=f"tropism_{i}_"
    out.append("  {")
    out.append("    TropismEntry t;")
    for axis,sfx in [("direction_x","dir_x"),("direction_y","dir_y"),("direction_z","dir_z"),("strength","strength")]:
        node=d[p+sfx]
        if isinstance(node,dict):
            out.append(f"    t.{axis}.mean = {fl(node['mean'])}; t.{axis}.deviation = {fl(node.get('deviation',0.0))};")
        else:
            out.append(f"    t.{axis}.mean = {fl(node)}; t.{axis}.deviation = 0.0f;")
    out.append(f"    t.usage_chance_percent = {fl(d[p+'usage_chance_percent'])};")
    orr=d[p+"order_response"]
    for ln in emit_plot("    t.order_response.mean", orr["mean"]): out.append("  "+ln.strip() if False else ln)
    for ln in emit_plot("    t.order_response.deviation", orr["deviation"]): out.append(ln)
    out.append("    d.tropisms.push_back(t);")
    out.append("  }")
out.append("}")
out.append("")
out.append("}  // namespace l_system_plugin")
open(sys.argv[2],"w").write("\n".join(out)+"\n")
print(f"wrote {sys.argv[2]}: {len(out)} lines, single={len(SINGLE)} plotted={len(PLOTTED)} curve={len(CURVE)} tropisms={n}")
